#!/usr/bin/env python3
"""Allowlisted GPU-server cache cleanup; results, scripts, data and installed envs are protected.

Dry run by default. GPU-active driver/solver caches are deferred.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import time


def size(path):
    if path.is_symlink():
        return 0
    if path.is_file():
        return path.stat().st_size
    total = 0
    for root, dirs, files in os.walk(path):
        dirs[:] = [d for d in dirs if not (Path(root)/d).is_symlink()]
        for name in files:
            p = Path(root)/name
            try:
                if not p.is_symlink(): total += p.stat().st_size
            except FileNotFoundError:
                pass
    return total


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--execute', action='store_true')
    ap.add_argument('--report', type=Path, required=True)
    ap.add_argument('--wait-for-idle', action='store_true', help='Defer cleanup until no CUDA processes remain')
    ap.add_argument('--max-wait-seconds', type=int, default=21600)
    args = ap.parse_args()
    if not Path('/root/SIM-EXP').is_dir():
        raise RuntimeError('This allowlist is only for the configured SIM-EXP GPU server')
    started = time.monotonic()
    while True:
        p = subprocess.run(['nvidia-smi', '--query-compute-apps=pid', '--format=csv,noheader'],
                           capture_output=True, text=True, check=True)
        pids = [int(x.strip()) for x in p.stdout.splitlines() if x.strip().isdigit()]
        if not args.wait_for_idle or not pids:
            break
        state = {'state':'waiting_for_gpu_idle','active_gpu_pids':pids,'executed':False}
        if time.monotonic()-started >= args.max_wait_seconds:
            state['state'] = 'deferred_active_job_still_running'
        args.report.parent.mkdir(parents=True,exist_ok=True)
        args.report.write_text(json.dumps(state,indent=2)+'\n')
        if state['state'] != 'waiting_for_gpu_idle':
            print(json.dumps(state)); return
        time.sleep(30)
    active_caches = set()
    for pid in pids:
        try:
            env = (Path('/proc')/str(pid)/'environ').read_bytes().split(b'\0')
            values = [v.split(b'=',1)[1].decode() for v in env if v.startswith(b'WARP_CACHE_PATH=')]
            if values:
                active_caches.update(Path(x).resolve() for x in values)
            elif 'warp' in (Path('/proc')/str(pid)/'maps').read_text():
                active_caches.add(Path('/root/.cache/warp').resolve())
        except (OSError, UnicodeError):
            active_caches.add(Path('/root/.cache/warp').resolve())
    targets = [Path(x) for x in (
        '/root/.cache/pip', '/root/.cache/uv', '/root/.cache/warp',
        '/root/.cache/torch_extensions', '/root/.cache/torch/kernels',
        '/root/.nv/ComputeCache', '/tmp/torchinductor_root',
        '/dev/shm/genesis-build', '/dev/shm/genesis-pip-cache')]
    targets += list(Path('/root/autodl-tmp').glob('warp-cache*'))
    targets += list(Path('/tmp').glob('wp_pch_*'))
    archives = [Path('/tmp/mjwarp-python.tar.gz'),
                Path('/root/autodl-tmp/genesis-runtime/libc6_2.35-0ubuntu3.18_amd64.deb')]
    archives += list(Path('/root/autodl-tmp/wheels').glob('warp_lang-*.whl'))
    targets += archives
    # Only generated bytecode inside this workspace; original Python scripts stay intact.
    for root, dirs, _ in os.walk('/root/SIM-EXP'):
        dirs[:] = [d for d in dirs if d != '.git' and not (Path(root)/d).is_symlink()]
        if '__pycache__' in dirs:
            targets.append(Path(root)/'__pycache__'); dirs.remove('__pycache__')
    usage_before = {x: shutil.disk_usage(x)._asdict() for x in ('/', '/root/autodl-tmp', '/dev/shm')}
    records, skipped = [], []
    for path in dict.fromkeys(targets):
        if not path.exists(): continue
        reason = None
        resolved = path.resolve()
        if resolved in active_caches:
            reason = 'active GPU process uses this solver cache'
        elif path == Path('/root/.nv/ComputeCache') and pids:
            reason = 'driver cache deferred while a GPU process is active'
        elif path.name.startswith('wp_pch_') and time.time()-path.stat().st_mtime < 600:
            reason = 'recent compiler workspace; may still be in use'
        if reason:
            skipped.append({'path':str(path),'reason':reason}); continue
        record = {'path':str(path),'logical_bytes':size(path)}
        if path in archives and path.is_file():
            with path.open('rb') as f: record['archive_sha256'] = hashlib.file_digest(f,'sha256').hexdigest()
            record['reason'] = 'download/installer archive; installed runtime preserved'
        else:
            record['reason'] = 'regenerable compiler, download, or bytecode cache'
        if args.execute:
            if path.is_dir() and not path.is_symlink(): shutil.rmtree(path)
            else: path.unlink()
        records.append(record)
    after = {x: shutil.disk_usage(x)._asdict() for x in usage_before}
    report = {'executed':args.execute,'recorded_at_utc':time.strftime('%Y-%m-%dT%H:%M:%SZ',time.gmtime()),
              'client_date':'2026-11-14','active_gpu_pids':pids,
              'before':usage_before,'after':after,'deleted' if args.execute else 'eligible':records,
              'skipped':skipped,
              'protected':['all experiment results and raw rollout artifacts','all authored scripts and audit snapshots',
                           'all manifests and provenance','raw datasets, models and weights',
                           'all installed runtime libraries and current environments',
                           '/root/autodl-tmp/outputs','/root/.cache/huggingface','/root/.cache/torch/hub']}
    args.report.parent.mkdir(parents=True,exist_ok=True)
    args.report.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({'executed':args.execute,'entries':len(records),'skipped':skipped,
                      'free_GiB':{x:round(v['free']/2**30,3) for x,v in after.items()}},indent=2))


if __name__ == '__main__':
    main()
